from history_svg import text


def _box(x, y, w, h, c, rx=12):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" class="{c} fillc"/>'


def _card(x, y, w, h, rx=12):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" class="box"/>'


def _svg(W, H, key, title, desc):
    return [f'<svg viewBox="0 0 {W} {H}" class="dg" role="img" aria-labelledby="cf{key}t cf{key}d">',
            f'<title id="cf{key}t">{title}</title>', f'<desc id="cf{key}d">{desc}</desc>']


def _lines(out, x, y, lines, cls='tnode2', anchor='middle', gap=17):
    for i, s in enumerate(lines):
        out.append(text(x, y + i * gap, s, cls, anchor))


