def _end(out, W, H, note):
    out.append(text(W / 2, H - 7, note, 'ts', 'middle'))
    out.append('</svg>')
    return '\n'.join(out)


def _tiers(tid, title, desc, tiers, note):
    W = 400
    H = 10 + sum(44 + len(t[2]) * 18 for t in tiers) + 20
    out = svg(W, H, tid, title, desc)
    y = 10
    for c, name, lines in tiers:
        h = 44 + len(lines) * 18
        out.append(box(8, y, 384, h - 6, c, '.13'))
        out.append(text(18, y + 21, name, 'tn'))
        for k, ln in enumerate(lines):
            out.append(text(28, y + 42 + k * 18, '· ' + ln, 'tw'))
        y += h
    return _end(out, W, H, note)


