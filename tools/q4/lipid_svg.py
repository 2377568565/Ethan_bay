# ---------------- 图：斑块是怎样长出来的 ----------------
def plaque():
    W, H = 400, 300
    out = svg(W, H, 'lpp', '斑块是怎样长出来的：从年轻时的“脂纹”到中年以后的心梗、中风',
              '示意图。第一步，血里的 LDL 太多、时间太久，一部分钻进动脉壁，被留在里面；第二步，身体派白细胞去清理，白细胞吞了太多胆固醇，变成“泡沫细胞”，堆成黄色的“脂纹”，'
              '这在年轻人身上就能看到；第三步，脂纹越堆越厚，外面包上一层纤维帽，成了“斑块”，血管变窄；第四步，斑块破裂，血小板聚过来形成血栓，'
              '堵在心脏就是心肌梗死，堵在脑子就是缺血性中风。高血压、高血糖、吸烟都会加速这个过程。')
    steps = [('① LDL 钻进动脉壁', 'LDL 越多、越久，钻进去的越多', 'f4'),
             ('② 白细胞吞胆固醇，变成泡沫细胞', '堆成黄色的“脂纹”：年轻人就有', 'f4'),
             ('③ 越堆越厚，包上纤维帽', '成了斑块，血管变窄', 'f6'),
             ('④ 斑块破裂，形成血栓', '堵在心脏＝心梗；堵在脑子＝中风', 'f6')]
    for i, (a, b, c) in enumerate(steps):
        y = 10 + i * 66
        out.append(f'<rect x="8" y="{y}" width="384" height="54" rx="10" class="box"/>')
        out.append(f'<rect x="8" y="{y}" width="6" height="54" rx="3" class="{c} fillc"/>')
        out.append(text(24, y + 22, a, 'tn'))
        out.append(text(24, y + 40, b, 'tw'))
        if i < 3:
            out.append(arrow(200, y + 55, 200, y + 65))
    out.append(text(200, 286, '高血压、高血糖、吸烟，都会让每一步走得更快（编者整理的示意）', 'ts', 'middle'))
    out.append('</svg>')
    return '\n'.join(out)


