from history_svg import text


def _box(x, y, w, h, c, rx=12):
    return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rx}" class="{c} fillc"/>'


def _svg(W, H, key, title, desc):
    return [f'<svg viewBox="0 0 {W} {H}" class="dg" role="img" aria-labelledby="un{key}t un{key}d">',
            f'<title id="un{key}t">{title}</title>', f'<desc id="un{key}d">{desc}</desc>']


def _lines(out, x, y, lines, cls='tnode2', anchor='middle', gap=18):
    for i, s in enumerate(lines):
        out.append(text(x, y + i * gap, s, cls, anchor))


