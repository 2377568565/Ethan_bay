# ---------------- 图：几股力量把肾脏的“设定点”调高 ----------------
def converge():
    W, H = 400, 330
    out = svg(W, H, 'htv', '为什么血压会慢慢升高：几股力量一起，把肾脏的“设定点”调高',
              '长期来说，血压由肾脏管：血压一高，肾脏就多排盐和水，把血压拉回来，这叫“压力—利钠”。'
              '左边是生活里的因素：盐多、钾少，体重增加，活动少，喝酒多，睡觉时打鼾憋气（睡眠呼吸暂停）。右边是随年龄和体质来的因素：大动脉变硬、遗传、少数人有肾上腺多分泌醛固酮等“继发”原因。'
              '它们都让肾脏要在更高的血压下才肯排出同样多的盐，于是血压被“设定”到了更高的位置。高血压又会让大动脉更硬，形成恶性循环。图是编者根据本页引用的研究整理的示意。')
