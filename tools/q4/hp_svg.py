# ---------------- 图：科雷亚级联 ----------------
def cascade():
    W = 400
    steps = [('f1', '慢性非萎缩性胃炎', '腺体还在 · 杀菌后可以恢复', ''),
             ('f3', '萎缩性胃炎', '腺体减少 · 杀菌后可能回退', '每年约 0.1%'),
             ('f4', '肠上皮化生（肠化）', '细胞像肠子 · 回头更难', '每年约 0.25%'),
             ('f5', '异型增生', '细胞开始不正常', '轻中度每年约 0.6%；重度约 6%'),
             ('f6', '胃癌', '早期可在胃镜下切除', '')]
    h, gap = 50, 8
    y0 = 8
    H = y0 + len(steps) * (h + gap) + 40
    out = svg(W, H, 'hpc', '从胃炎到胃癌：一条走了几十年的台阶',
              '科雷亚描述的肠型胃癌发生过程：慢性非萎缩性胃炎、萎缩性胃炎、肠上皮化生、异型增生、胃癌。幽门螺杆菌和吃盐多与开头的胃炎和萎缩有关。'
              '荷兰全国资料：确诊后每年发生胃癌的比例，萎缩性胃炎约 0.1%，肠化约 0.25%，轻中度异型增生约 0.6%，重度异型增生 5 年内每年约 6%。'
              '越往上走，回头越难；在第一级杀菌，好处最大。')
    for i, (c, name, sub, risk) in enumerate(steps):
        y = y0 + i * (h + gap)
        x = 8 + i * 22
        w = 384 - i * 22
        out.append(box(x, y, w, h, c, '.14'))
        out.append(f'<rect x="{x + 8}" y="{y + 8}" width="6" height="{h - 16}" rx="3" class="{c} fillc"/>')
        out.append(text(x + 22, y + 22, name, 'tn'))
        out.append(text(x + 22, y + 39, sub, 'ts'))
        if risk:
            out.append(text(392 - 8, y + 22, risk, 'tw', 'end'))
    y = y0 + len(steps) * (h + gap)
    out.append(text(8, y + 12, '↑ 幽门螺杆菌、盐、吸烟推着往上走', 'tw'))
    out.append(text(8, y + 30, '右边：确诊后每年变成胃癌的比例 · Correa 1992、de Vries 2008', 'ts'))
    out.append('</svg>')
    return '\n'.join(out)


